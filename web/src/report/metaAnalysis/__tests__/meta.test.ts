// Combining experiments (P-92): the payload read from a grouped table,
// option normalising, the strings of the results sheet and headline, the
// checks, and the forest plot's rows and CI ends.
// Run: npm run test:unit
import { test } from "node:test";
import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { DEFAULT_META, FORMAT_ERROR, metaPayload, normalizeMeta, runMeta } from "../run.ts";
import {
  heterogeneityRows, metaHeadline, metaMethodsText, pooledRows, shown, studyRows,
} from "../format.ts";
import { FOREST_DEFAULTS, forestFigure, forestRows } from "../forest.ts";
import { keyFacts } from "../../../components/answer/keyFacts.ts";
import { metaChips } from "../../../guide/checks.ts";
import { CHROME_LIGHT } from "../../../lib/palette.ts";
import type { DataTableModel } from "../../../project/types.ts";

// engine output for dat.bcg (log risk ratios, SE) as typed with 6
// decimals; generated by the engine's meta_analysis handler. metafor
// prints REML -0.7145, tau^2 0.3132, I^2 92.22% (rma.uni Examples), and
// engine/tests/reference/meta_reference.py gives the Hartung-Knapp CI
// -1.1084 to -0.3206.
const BCG = JSON.parse(readFileSync(new URL("./bcg-result.json", import.meta.url), "utf8"));

function grouped(rows: string[][], format: DataTableModel["subcolumnFormat"] = "mean_sem",
  titles?: string[]): DataTableModel {
  return {
    type: "grouped", x: rows.map(() => ""), rowTitles: titles ?? rows.map((_, i) => `E${i + 1}`),
    subcolumnFormat: format, subcolumns: rows[0].length,
    datasets: [{ name: "log RR", rows: rows.map((r) => [...r]) }],
  } as unknown as DataTableModel;
}

test("payload: rows with a value become experiments, blank rows are skipped", () => {
  const t = grouped([["-0.5", "0.2"], ["", ""], ["0.1", ""], ["0.3", "0.1"]]);
  const p = metaPayload(t, DEFAULT_META);
  assert.ok("payload" in p);
  const pl = p.payload as any;
  assert.equal(pl.analysis, "meta_analysis");
  assert.deepEqual(pl.data.rows.map((r: any) => r.label), ["E1", "E3", "E4"]);
  assert.deepEqual(pl.data.rows[1].values, [0.1, null]);
  assert.equal(pl.options.format, "mean_sem");
  assert.equal(pl.options.test, "knha");
  assert.equal(pl.options.method, "REML");
  assert.equal(pl.options.name, "log RR");
});

test("payload: Mean, upper, lower is sent as mean_limits; replicates are refused", () => {
  const t = grouped([["0.5", "0.8", "0.3"]], "upper_lower");
  const p = metaPayload(t, { ...DEFAULT_META, scale: "ratio", limitsLevel: 0.9 }) as any;
  assert.equal(p.payload.options.format, "mean_limits");
  assert.equal(p.payload.options.limits_level, 0.9);
  const r = runMeta({ analyze: () => { throw new Error("not called"); } },
    grouped([["1", "2"]], "replicates"), DEFAULT_META);
  assert.equal(r.error, FORMAT_ERROR);
});

test("normalizeMeta keeps valid options and resets the rest", () => {
  assert.deepEqual(normalizeMeta(null), DEFAULT_META);
  assert.deepEqual(normalizeMeta({ dataset: 2, scale: "ratio", method: "DL", test: "z", ciLevel: 0.9 }),
    { ...DEFAULT_META, dataset: 2, scale: "ratio", method: "DL", test: "z", ciLevel: 0.9 });
  assert.deepEqual(normalizeMeta({ dataset: -1, scale: "odd", ciLevel: 0.42 }), DEFAULT_META);
});

test("results strings: dat.bcg pooled rows and heterogeneity", () => {
  const rows = studyRows(BCG);
  assert.equal(rows.length, 13);
  assert.equal(rows[0].label, "Aronson 1948");
  const pooled = pooledRows(BCG);
  assert.equal(pooled[0].label, "Common effect (inverse variance)");
  assert.equal(pooled[0].estimate, "-0.4303");
  assert.equal(pooled[1].label, "Random effects (REML, Hartung-Knapp)");
  assert.equal(pooled[1].estimate, "-0.7145");
  assert.equal(pooled[1].ratio, "0.4894");
  assert.equal(pooled[1].ci, "0.3301 to 0.7257");
  assert.equal(pooled[2].label, "Prediction interval (a new experiment)");
  const het = Object.fromEntries(heterogeneityRows(BCG));
  assert.equal(het["τ² (REML)"], "0.3132 (SE 0.1664)");
  assert.equal(het["I²"], "92.22%");
  assert.equal(het["Cochran's Q (12 df)"].startsWith("152.2"), true);
  assert.deepEqual(shown(BCG.random, "difference"), { value: "-0.7145", ci: "-1.108 to -0.3206" });
});

test("headline: the random-effects ratio with its Hartung-Knapp CI", () => {
  const h = metaHeadline(BCG);
  assert.equal(h.title, "log RR: 13 experiments combined");
  assert.equal(h.name, "Pooled ratio, random effects");
  assert.equal(h.value, "0.4894");
  assert.equal(h.ci, "95% CI 0.3301 to 0.7257 (Hartung-Knapp)");
  assert.deepEqual(h.facts.slice(0, 2), ["τ² 0.3132", "I² 92.22%"]);
  const k = keyFacts(BCG);
  assert.ok(k && k.kind === "figures");
  assert.equal(k.items[0].figure?.value, "0.4894");
});

test("methods text names REML, Hartung-Knapp and the prediction interval", () => {
  const t = metaMethodsText(BCG);
  assert.match(t, /13 experiments were combined/);
  assert.match(t, /restricted maximum likelihood/);
  assert.match(t, /Hartung-Knapp method \(t distribution on 12 df/);
  assert.match(t, /prediction interval for a new experiment \(t distribution on 11 df/);
  assert.doesNotMatch(t, /—/);
});

test("checks: few experiments warn, the z interval is called too narrow", () => {
  const three = { ...BCG, k: 3, random: { ...BCG.random, test: "z" }, dropped: [{ label: "E4", reason: "SE is not positive" }] };
  const chips = metaChips(three);
  const few = chips.find((c) => c.id === "meta-few")!;
  assert.equal(few.state, "warn");
  assert.match(few.detail, /too narrow/);
  assert.equal(chips.find((c) => c.id === "meta-dropped")?.detail, "E4: SE is not positive.");
  assert.equal(metaChips(BCG).find((c) => c.id === "meta-few")?.state, "ok");
  assert.equal(metaChips(BCG).find((c) => c.id === "meta-het")?.state, "warn");
});

test("forest rows: 13 experiments, the pooled rows and CI ends equal the engine's", () => {
  const rows = forestRows(BCG, FOREST_DEFAULTS);
  assert.equal(rows.filter((r) => r.kind === "study").length, 13);
  assert.deepEqual(rows.slice(13).map((r) => r.kind), ["fixed", "random", "prediction"]);
  const re = rows.find((r) => r.kind === "random")!;
  assert.equal(re.value, BCG.random.ratio);
  assert.deepEqual([re.lo, re.hi], BCG.random.ratio_ci);
  assert.deepEqual([rows[0].lo, rows[0].hi], BCG.studies[0].ratio_ci);
  assert.equal(forestRows(BCG, { pooled: "none", prediction: true }).length, 13);
  assert.equal(forestRows(BCG, { pooled: "fixed", prediction: true }).length, 14);
});

test("forest figure: log axis at ratio 1, diamond spans the CI", () => {
  const f = forestFigure({ result: BCG, settings: FOREST_DEFAULTS, chrome: CHROME_LIGHT,
    font: "Inter", accent: "#1f77b4", xTitle: "Ratio" });
  assert.equal((f.layout.xaxis as any).type, "log");
  assert.equal((f.layout.shapes as any[])[0].x0, 1);
  const diamond = f.traces.find((t: any) => t.name === "Random effects") as any;
  assert.equal(Math.min(...diamond.x), BCG.random.ratio_ci[0]);
  assert.equal(Math.max(...diamond.x), BCG.random.ratio_ci[1]);
  const pts = f.traces[0] as any;
  assert.equal(pts.x.length, 13);
  const diff = forestFigure({ result: { ...BCG, scale: "difference" }, settings: FOREST_DEFAULTS,
    chrome: CHROME_LIGHT, font: "Inter", accent: "#1f77b4", xTitle: "" });
  assert.equal((diff.layout.xaxis as any).type, "linear");
  assert.equal((diff.layout.shapes as any[])[0].x0, 0);
});

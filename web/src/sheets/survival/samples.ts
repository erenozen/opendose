/** time, event (0/1), age, sex (1 male, 2 female). */
export function lungRows(): [string, string, string, string][] {
  return LUNG.trim().split(/\s+/).map((r) => r.split(",") as [string, string, string, string]);
}

/** Survival table: one group per sex, Age as a covariate column. */
export function lungSurvivalTable(): DataTableModel {
  const rows = lungRows();
  const group = (sex: string) => rows.filter((r) => r[3] === sex).map((r) => [r[0], r[1], r[2]]);
  return normalizeTable({
    type: "survival",
    datasets: [
      { name: "Male", subTitles: ["Time", "Event", "Age"], rows: group("1") },
      { name: "Female", subTitles: ["Time", "Event", "Age"], rows: group("2") },
    ],
  });
}

/** Multiple-variables table: days, status (1 censored, 2 died, as in R),
 *  age and sex as text. */
export function lungVariablesTable(): DataTableModel {
  const rows = lungRows();
  return normalizeTable({
    type: "multivariable",
    datasets: [
      { name: "Days", varType: "continuous", rows: rows.map((r) => [r[0]]) },
      { name: "Status", varType: "continuous", rows: rows.map((r) => [String(Number(r[1]) + 1)]) },
      { name: "Age", varType: "continuous", rows: rows.map((r) => [r[2]]) },
      { name: "Sex", varType: "categorical", rows: rows.map((r) => [r[3] === "1" ? "Male" : "Female"]) },
    ],
  });
}

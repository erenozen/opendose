// Regenerate src/app/sampleResults.json: the example project's results as
// the engine computes them, shown at first paint (marked as not live)
// until the live engine has recomputed them. Run against a dev server
// after engine changes that move the example's numbers:
//   node scripts/gen-sample-results.mjs [http://localhost:5201/]
import { writeFileSync } from "node:fs";
import { chromium } from "playwright";

const base = process.argv[2] ?? "http://localhost:5201/";
const out = new URL("../src/app/sampleResults.json", import.meta.url);
const browser = await chromium.launch();
const page = await browser.newPage();
await page.goto(new URL("?example=1", base).href, { waitUntil: "domcontentloaded" });
await page.waitForSelector('.pane-results[data-live="true"] .results-table', { timeout: 240000 });
// Every results sheet of the example, computed live (the hidden ones in
// the background).
const results = await page.waitForFunction(() => {
  const app = globalThis.__opendose;
  if (!app) return null;
  const sheets = app.store.project.sheets.filter((s) => s.kind === "results");
  const rows = sheets.map((s) => {
    const e = app.results.get(s.id);
    return e && e.live ? { analysis: s.analysis, result: e.result } : null;
  });
  return rows.every(Boolean) ? rows : null;
}, null, { timeout: 240000, polling: 250 }).then((h) => h.jsonValue());
await browser.close();
const bad = results.filter((r) => r.result && typeof r.result === "object" && r.result.error);
if (bad.length) throw new Error(`example results with errors: ${JSON.stringify(bad).slice(0, 300)}`);
writeFileSync(out, `${JSON.stringify({
  note: "Generated by scripts/gen-sample-results.mjs; shown until the live engine recomputes.",
  generated: new Date().toISOString().slice(0, 10),
  results,
})}\n`);
console.log(`wrote ${results.length} results to ${out.pathname}`);

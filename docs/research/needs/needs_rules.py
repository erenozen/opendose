"""Clustering rules for the user-needs catalogue.

Each entry of NEEDS is one *need*: something a tool would have to do. An
observation (one row of raw/*.json) is assigned to exactly one need by
`build_catalogue.py`:

  score(need, obs) = 3.0 x (patterns of `kw` that match the observation's `need` text)
                   + 1.5 x (patterns of `kw` that match its `problem` text)
                   + 0.5 x (patterns of `kw` that match its quote or workflow)
                   + 2.5 if the observation's first tag is in `tags`
                   + 1.0 x (its other tags that are in `tags`)
                   - 3.0 if the need is `generic` (a catch-all)

A need is a candidate only when at least one `kw` pattern matches the
`need` or `problem` text, and, if it has `req`, when `req` matches the
observation's need + problem + workflow + tags. `excl` (matched against the
`need` text) removes the candidate. The highest score wins; ties go to the
need listed first. Observations with no candidate fall back to the need
that FALLBACK names for their first tag (then for their other tags).

Status judgements (`status`, `why`, `gap`) cite README.md, docs/ROADMAP.md,
web/src/sheets/README.md, web/src/guide/explainers.ts,
web/src/guide/recommend.ts or engine/opendose/api.py handler names, as of
2026-10-09. `hidden` marks needs that are met but hard to find: the
proposal is about discoverability. `research` marks needs that need a
design study before any build. `effort` is S (days), M (one to two weeks),
L (more). `accept` is the acceptance test a user would recognise.
"""

